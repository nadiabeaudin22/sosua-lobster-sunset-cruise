let lang = localStorage.getItem("siteLang") || "en";

const selector = document.getElementById("languageSelect");
selector.value = lang;

function applyLanguage(next) {
  lang = next;
  localStorage.setItem("siteLang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[lang][key]) {
      el.textContent = t[lang][key];
    }
  });
}

selector.addEventListener("change", (e) => {
  applyLanguage(e.target.value);
});

const guests = document.getElementById("guests");
const totalPrice = document.getElementById("totalPrice");
const depositPrice = document.getElementById("depositPrice");
const balancePrice = document.getElementById("balancePrice");
const date = document.getElementById("date");
const formMessage = document.getElementById("formMessage");

function updatePrice() {
  const n = Math.max(1, Number(guests.value) || 1);
  const total = n * PRICE;
  const deposit = total / 2;

  totalPrice.textContent = `US$${total}`;
  depositPrice.textContent = `US$${deposit}`;
  balancePrice.textContent = `US$${total - deposit}`;
}

function validDay(value) {
  if (!value) return false;

  const day = new Date(`${value}T12:00:00`).getDay();

  return [0, 4, 5, 6].includes(day);
}

guests.addEventListener("input", updatePrice);

date.addEventListener("change", () => {
  formMessage.textContent =
    date.value && !validDay(date.value)
      ? t[lang].invalidDay
      : "";
});

document
  .getElementById("bookingForm")
  .addEventListener("submit", (e) => {
    e.preventDefault();

    if (!validDay(date.value)) {
      formMessage.textContent = t[lang].invalidDay;
      return;
    }

    const n = Math.max(1, Number(guests.value) || 1);
    const total = n * PRICE;
    const deposit = total / 2;

    const name = document.getElementById("name").value.trim();
    const phone = document.getElementById("phone").value.trim();
    const pasta = document.getElementById("pasta").value;
    const notes = document.getElementById("notes").value.trim();

    const message = [
      t[lang].hello,
      "",
      `Name / Nom / Nombre: ${name}`,
      `Phone / WhatsApp: ${phone}`,
      `Date: ${date.value}`,
      `Guests / Personnes / Personas: ${n}`,
      `Pasta: ${pasta}`,
      `Total: US$${total}`,
      `Deposit / Dépôt / Depósito: US$${deposit}`,
      `Balance: US$${total - deposit}`,
      "Meeting point: 108 Playa Sosúa, El Velero",
      notes ? `Notes: ${notes}` : ""
    ]
      .filter(Boolean)
      .join("\n");

    window.open(
      `https://wa.me/${WHATSAPP}?text=${encodeURIComponent(message)}`,
      "_blank"
    );
  });

applyLanguage(lang);
updatePrice();
